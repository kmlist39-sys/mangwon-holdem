function betweenHeroHands(t){
 // Consolidation can coincide with the break or span multiple thresholds
 // after a large multiway elimination. Only settle the tables being retired.
 for(let closing; (closing=closingTable());){
   if(closing.phase!=='done'&&!breakDue()&&aliveAt(t)>=2)break;
   finishOffscreen(closing);closeTable(closing);
 }
 if(breakDue()){
   for(const u of g.ts.slice(1))finishOffscreen(u);
   for(let closing; (closing=closingTable());)closeTable(closing);
   for(const u of g.ts.slice(1))readyRoster(u);
 }
 if(aliveAt(t)<2&&g.ts.length>1){
   const donor=g.ts.slice(1).reduce((a,b)=>aliveAt(a)>aliveAt(b)?a:b);
   finishOffscreen(donor);if(!closeTable(donor))readyRoster(donor);
 }
}

