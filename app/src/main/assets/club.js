function accountFinished(t){
 if(g.cash){washCash(t);return}
 if(t.phase==='done'&&t.pendingTournamentEvents?.length)flushTournamentEvents(t);
 if(t.accounted||!['done','showdown'].includes(t.phase))return;
 t.accounted=true;t.reentries=[];
 const busted=t.ps.filter(p=>p.stack===0).sort((a,b)=>a.start-b.start||a.id-b.id);
 const groups=[];
 for(const p of busted){
   tournamentEvent(t,p,'eliminated');
   if(p.id!==-1&&entryOpen(t)&&Math.random()<.55){
     registerRebuy(t,p);t.reentries.push(p.id);
   }else if(!g.exits.includes(p.id)){
     g.exits.push(p.id);
     if(groups.length&&groups[groups.length-1][0].start===p.start)groups[groups.length-1].push(p);
     else groups.push([p]);
   }
 }
 for(const group of groups){
   if(group.length<2||g.prizePlan?.sharedPlaces===false)continue;
   // Seats clockwise from the button receive an indivisible point first.
   const n=t.ps.length,order=p=>(t.ps.indexOf(p)-t.btn-1+n)%n;
   (g.prizeTies??=[]).push(group.sort((a,b)=>order(a)-order(b)).map(p=>p.id));
 }
}
function aliveAt(t){
 return t.ps.filter(p=>!g.exits.includes(p.id)).length+(t.inbound?.length||0);
}
function prepareRoster(t){
 if(t.rosterReady)return;
 accountFinished(t);
 for(const p of t.ps)if(t.reentries?.includes(p.id)){
   p.stack=p.pendingRebuyStack??START_STACK;delete p.pendingRebuyStack;
 }
 t.reentries=[];
 const survivors=[];
 for(let k=1;k<=t.ps.length;k++){
   const p=t.ps[(t.btn+k+t.ps.length)%t.ps.length];
   if(p.stack>0)survivors.push(p);
 }
 t.ps=survivors;t.btn=-1;t.rosterReady=true;
}
function receiveTransfers(t){
 if(!t.inbound?.length)return;
 // Preserve the next dealer and small blind; the first arrival posts the next big blind.
 t.ps.splice(Math.min(2,t.ps.length),0,...t.inbound);
 t.inbound=[];
}
function shortestTable(tables){
 return tables.reduce((best,t)=>!best||aliveAt(t)<aliveAt(best)||aliveAt(t)===aliveAt(best)&&t.number<best.number?t:best,null);
}
function closingTable(){
 if(g.ts.length<2)return null;
 // Protect a seat for an eliminated player who can still accept a rebuy.
 const t=g.ts[0],hero=t.ps.find(p=>p.id===-1);
 const reserve=g.exits.includes(-1)&&hero&&entryOpen(t)?1:0;
 if(g.entrants-g.exits.length+reserve>(g.ts.length-1)*g.capacity)return null;
 return g.ts.slice(1).reduce((best,u)=>!best||aliveAt(u)<aliveAt(best)||aliveAt(u)===aliveAt(best)&&u.number>best.number?u:best,null);
}
function sendSeat(p,from,to,reason){
 (to.inbound||=[]).push(p);
 g.lastTransfer={id:p.id,name:nameOf(p.id),from:from.number,to:to.number,hand:from.hand,reason};
 msg(nameOf(p.id)+' · '+from.number+'번 → '+to.number+'번 테이블');
}
function balanceFrom(t){
 const closing=closingTable();if(closing===t)return;
 const recipients=g.ts.filter(u=>u!==t&&u!==closing);
 for(;;){
   const dest=shortestTable(recipients);
   if(!dest||aliveAt(t)-aliveAt(dest)<2||aliveAt(dest)>=g.capacity)return;
   const nextBB=t.ps.length===2?1:2;
   let i=nextBB%t.ps.length;
   if(t.ps[i].id===-1)i=(i+1)%t.ps.length;
   const [p]=t.ps.splice(i,1);sendSeat(p,t,dest,'balance');
 }
}
function closeTable(t){
 // Only the retiring table must have finished its hand. Each receiving table
 // owns its present cards, button and seats until its next deal.
 if(t.phase!=='done'||t===g.ts[0]||closingTable()!==t)return false;
 prepareRoster(t);receiveTransfers(t);
 const recipients=g.ts.filter(u=>u!==t);
 for(const p of t.ps){const dest=shortestTable(recipients);sendSeat(p,t,dest,'closure');}
 g.ts=recipients;
 g.lastClosed={number:t.number,remaining:recipients.length};
 if(!g.cash&&recipients.length===1&&!g.finalTablePlayed)g.finalTablePending=true;
 msg(recipients.length===1?'파이널 테이블 합석':t.number+'번 테이블 종료 · '+recipients.length+'개 테이블 진행');
 return true;
}
