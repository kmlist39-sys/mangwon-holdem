function liveStudyGuide(t,p){
 const spot=studyDecision(t,p),legal=canRaise(t,p);
 const share=spot.equity/100,required=spot.odds/100;
 const river=t.stage===3,playingLast=t.actor===t.btn;
 const realization=river?1:cap(.92+(playingLast?.06:0)-.035*(spot.opponents-1),.72,.98);
 const edge=share*realization-required;
 const continueRate=spot.call?1/(1+Math.exp(-edge/.050)):1;
 const draw=t.stage>0?t.boards.reduce((n,b)=>n+handTexture(p.hole,b).draw,0)/t.boards.length:0;
 const value=cap((share-(spot.opponents>1?.53:.58))/.32,0,1);
 const aggression=legal?cap(.025+.78*value+draw*(playingLast?.55:.40)+(playingLast?.035:0),0,.93):0;
 const fold=spot.call?Math.round(100*(1-continueRate)):0;
 const raise=legal?Math.min(100-fold,Math.round((100-fold)*aggression)):0;
 const bet=legal?quickBets(t,p).half.target:0;
 return {pot:spot.pot,eligible:spot.eligible,call:spot.call,odds:spot.odds,equity:spot.equity,
   position:spot.position,fold,passive:100-fold-raise,raise,canRaise:legal,raiseTo:bet,
   opening:t.price===0,allInRaise:legal&&bet===p.bet+p.stack,allInCall:spot.call>0&&spot.call===p.stack,
   title:spot.title,reason:spot.reason};
}
function handTexture(h,board){
 if(h.length===3){
   const pairs=[[h[0],h[1]],[h[0],h[2]],[h[1],h[2]]].map(pair=>handTexture(pair,board));
   return {draw:Math.max(...pairs.map(x=>x.draw)),blocker:Math.max(...pairs.map(x=>x.blocker)),wet:pairs[0].wet};
 }
 const b=boardMasks(board);
 let cards=0,draw=0,blocker=0,wet=b.pairs?.14:0;
 for(const card of h){
   const suit=Math.floor(card/13),rank=card%13+2;cards|=1<<rank;
   const suited=h.filter(x=>Math.floor(x/13)===suit).length;
   if(board.length<5&&b.counts[suit]+Math.min(2,suited)===4)draw=Math.max(draw,.26+(rank===14?.06:0));
   if(b.counts[suit]>=3&&rank===highBit(32764&~b.suits[suit]))blocker=Math.max(blocker,.85);
 }
 wet+=Math.max(...b.counts)>=3?.28:Math.max(...b.counts)===2?.12:0;
 let both=b.bits|cards,pure=b.bits;if(both&(1<<14))both|=2;if(pure&(1<<14))pure|=2;
 let outs=0;
 for(let high=5;high<=14;high++){
   const window=31<<(high-4),missing=window&~both,boardMissing=window&~pure;
   if(missing&&(missing&(missing-1))===0&&missing!==boardMissing)outs|=missing;
   if(boardMissing&&(boardMissing&(boardMissing-1))===0){
     wet=Math.max(wet,.50);if(window&cards&~pure)blocker=Math.max(blocker,.55);
   }
 }
 if(board.length<5&&outs)draw=Math.max(draw,outs&(outs-1)?.23:.105);
 return {draw,blocker,wet:Math.min(.75,wet)};
}
function masterDecision(t,p,bubble,background=false){
 const opponents=opponentsFor(t,p),multi=opponents.length,pos=positionScore(t),bb=t.bb;
 const cost=Math.min(owing(t,p),p.stack),pot=t.ps.reduce((s,q)=>s+q.paid,0);
 const eligible=t.ps.reduce((s,q)=>s+Math.min(q.paid,p.paid+(cost||p.stack)),0),odds=cost/(eligible+cost||1);
 const effective=Math.min(p.stack,Math.max(...opponents.map(o=>o.stack+Math.max(0,o.bet-p.bet))));
 const spr=effective/Math.max(bb,pot),aggression=people[p.id].agg,trait=people[p.id].trait||traits[p.id];
 const live=opponents.filter(o=>o.stack>0),willFold=live.length?live.reduce((s,o)=>s+o.fold,0)/live.length:0;
 const covers=live.length>0&&live.every(o=>p.stack>=o.stack*1.2);
 const payoutRisk=bubble?(covers&&trait==='pressure'?-.025:.035):0;
 const mayRaise=canRaise(t,p);
 function raiseBy(increase){
   const max=p.bet+p.stack,minimum=Math.min(max,t.price+t.raise);
   const target=t.price+Math.max(t.raise,Math.round(increase/Math.max(1,bb/4))*Math.max(1,bb/4));
   return ['raise',cap(target,minimum,max)];
 }
 if(t.stage===0){
   const quality=rangeGrade(p.hole,[]),raised=t.price>bb;
   const limpers=t.ps.filter(q=>q!==p&&!q.fold&&q.line?.preCall).length;
   const stackBB=(effective+cost)/bb,priceBB=t.price/bb;
   const cut=.67-pos*.17+(multi>4?.03:0)+payoutRisk-cap(willFold-.42,-.12,.22)*(trait==='steal'?.33:.20);
   if(!raised){
     if(mayRaise&&quality>=cut){
       if(stackBB<=10&&quality>=cut+.025)return raiseBy(effective+cost);
       return raiseBy(bb*(1.25+limpers*.85+(1-pos)*.5));
     }
     if(!cost)return ['call'];
     return quality>=cut-.095&&odds<.22&&limpers>0?['call']:['fold'];
   }
   const eq=masterEquity(p.hole,t.boards,opponents,background?14:0).share;
   const premium=.90+(priceBB>8?.045:0)-(stackBB<=12?.09:0);
   const wheelAce=p.hole.some(c=>c%13===12)&&Math.floor(p.hole[0]/13)===Math.floor(p.hole[1]/13)&&quality<.68;
   const blindDefense=t.actor===t.bbSeat||t.actor===t.sbSeat;
   const steal=wheelAce&&(pos>.65||blindDefense)&&priceBB<=3.5&&limpers<=1&&Math.random()<cap(.08+(willFold-.42)*.65,.04,.25);
   if(mayRaise&&(quality>=premium||steal))return raiseBy(stackBB<18||priceBB>stackBB*.24?effective+cost:t.price*(2+(1-pos)*.65));
   const realization=.77+pos*.15+(quality>.80?.07:0)+(t.actor===t.bbSeat&&priceBB<=2.6?.045:0);
   return cost&&eq*realization<odds+.018+payoutRisk?['fold']:['call'];
 }
 const rollout=masterEquity(p.hole,t.boards,opponents,background?16:0),eq=rollout.share;
 const texture=t.boards.map(b=>handTexture(p.hole,b));
 const average=key=>texture.reduce((s,q)=>s+q[key],0)/texture.length;
 const draw=average('draw'),blocker=average('blocker'),wet=average('wet'),river=t.stage===3;
 const activeRivals=live.length,heads=multi===1;
 const thin=trait==='value'&&heads&&river&&!cost?.065:0;
 const freeroll=t.double&&rollout.scoop>.24&&eq>.55;
 const goodValue=eq>(heads?.62:.54)+(cost?.08:0)+payoutRisk-thin||(trait==='split'&&freeroll);
 const foldEquity=Math.pow(cap(willFold+.08*pos,.15,.77),activeRivals);
 const blockerBluff=river&&blocker>.50&&eq<.28&&spr>.55;
 const semiBluff=!river&&draw>=.20&&eq>.14&&spr>.55;
 const checkRaise=cost>0&&p.line?.lastCheck===t.stage&&p.line?.lastRaise!==t.stage;
 const oop=live.some(o=>o.stack>0)&&t.ps.some((q,i)=>q!==p&&!q.fold&&q.stack>0&&((i-t.btn-1+t.ps.length)%t.ps.length)>pos*(t.ps.length-1)+.001);
 // Protect the checking range against the last aggressor. Texture and position
 // influence how often both sets and strong draws check to induce a bet.
 if(!cost&&oop&&!river&&p.line?.lastRaise!==t.stage&&spr>.8){
   const initiative=t.ps.some(q=>q!==p&&!q.fold&&(t.stage===1?q.line?.preRaise:q.line?.lastRaise===t.stage-1));
   const checkChance=cap((initiative?.66:.29)+(wet<.23?.10:-.13)+(trait==='trap'?.10:0)-(multi-1)*.045,.12,.86);
   if((goodValue||semiBluff)&&Math.random()<checkChance)return ['call'];
 }
 if(mayRaise&&checkRaise){
   const value=eq>(heads?.72:.64)+payoutRisk;
   const aggressionRead=live.reduce((sum,o)=>sum+o.aggression,0)/Math.max(1,live.length);
   const valueMix=cap(.73+aggressionRead*.37+(wet>.28?.07:0),.7,.96);
   const bluffMix=cap((river?.14:.23)+(willFold-.42)*.40+(trait==='draw'?.055:0)-.08*(multi-1),.025,.4);
   const candidate=semiBluff||blockerBluff;
   if((value&&Math.random()<valueMix)||(!value&&candidate&&Math.random()<bluffMix)){
     const increment=Math.max(cost*(wet>.28?2.35:1.95),(pot+cost)*(river?.69:.53));
     return raiseBy(spr<1.35&&value?effective+cost:increment);
   }
 }
 const deep=trait==='pressure'&&spr>3&&pos>.5;
 const frequency=foldEquity*(.37+aggression*.34+(deep?.12:0))*(cost?.46:1);
 if(mayRaise&&!checkRaise&&(goodValue||((semiBluff||blockerBluff)&&Math.random()<frequency))){
   const fraction=goodValue?(wet>.32?.76:river?.66:.48):(river?.82:.61);
   return raiseBy(spr<=1.1&&goodValue?effective+cost:(pot+cost)*fraction);
 }
 const realization=river?1:cap(.82+.11*pos+(spr<1?.10:0)-.022*(multi-1),.68,1);
 const read=trait==='catch'&&heads&&river?(opponents[0].aggression-.25)*.12:0;
 const sizeTax=trait==='control'&&cost>eligible*.65?.035:0;
 if(cost&&eq*realization+draw*.035+read<odds+payoutRisk+sizeTax)return ['fold'];
 return ['call'];
}
function cast(pub,n){
 const seated=new Set();
 for(const game of state.parked||[])for(const table of game?.ts||[])for(const q of table.ps)seated.add(q.id);
 const available=shuffle(people.filter(p=>!seated.has(p.id)));
 const pool=[...available.filter(p=>p.pub===pub),...available.filter(p=>p.pub!==pub)];
 const regulars=pool.filter(p=>p.skill==='일반인'),experts=pool.filter(p=>p.tier===2);
 const guests=pool.filter(p=>p.tier!==2&&p.skill!=='일반인');
 // Even if Mapo opens first, leave a broadcaster from each other venue for its next visit.
 const reserved=new Set();
 for(let other=0;other<3;other++)if(other!==pub&&!state.parked?.[other]){
   const guest=guests.find(p=>p.pub===other&&p.skill==='BJ');
   if(guest)reserved.add(guest.id);
 }
 const away=guests.filter(p=>reserved.has(p.id));
 const mixed=guests.filter(p=>!reserved.has(p.id));
 const tables=[];
 let totalRegulars=0;
 for(let seats=n;seats>0;){
   const size=Math.min(seats,tables.length?9:8);
   const ordinary=Math.min(size,size<=5?3:5);
   const featured=experts.shift(),players=featured?[featured]:[];
   if(tables.length===0){
     const guest=mixed.findIndex(p=>p.skill==='BJ');
     if(guest>=0)players.push(mixed.splice(guest,1)[0]);
   }
   tables.push({size,ordinary:Math.min(ordinary,size-players.length),players});
   totalRegulars+=tables[tables.length-1].ordinary;
   seats-=size;
 }
 // Share the spare regulars proportionally across all three live fields. This
 // avoids draining the entire neighborhood into whichever tournament opens first.
 const target=Math.min(regulars.length,Math.max(totalRegulars,Math.round(n*regulars.length/pool.length)));
 const order=shuffle([...tables]);
 while(totalRegulars<target){
   const previous=totalRegulars;
   for(const table of order)if(totalRegulars<target&&table.ordinary+table.players.length<table.size){
     table.ordinary++;totalRegulars++;
   }
   if(totalRegulars===previous)break;
 }
 // Seed everyone before filling leftovers, so every individual side table has
 // the intended majority. Depleted or migrated saves can still fill each seat.
 for(const t of tables)t.players.push(...regulars.splice(0,t.ordinary));
 const otherPlayers=[...mixed,...experts,...away,...regulars];
 const ids=[];
 for(const t of tables){
   t.players.push(...otherPlayers.splice(0,t.size-t.players.length));
   ids.push(...shuffle(t.players).map(p=>p.id));
 }
 return ids;
}

